"""Local request/job correlation without collecting request or client data.

IDs are generated by this process, never trusted from incoming headers. The
context is copied by asyncio tasks and restored after every request/job scope.
This module does not configure exporters or perform network activity.
"""

from __future__ import annotations

import asyncio
from contextlib import contextmanager
from contextvars import ContextVar
import re
import time
from typing import Iterator, Literal
from uuid import uuid4

from fastapi import FastAPI
from starlette.types import ASGIApp, Message, Receive, Scope, Send


REQUEST_ID_HEADER = "X-Request-ID"
_CONTEXT: ContextVar[dict[str, str] | None] = ContextVar("basswiesn_correlation", default=None)
_ID = re.compile(r"[a-f0-9]{32}\Z")
_METHODS = frozenset({"GET", "HEAD", "POST", "PUT", "PATCH", "DELETE", "OPTIONS", "TRACE", "CONNECT"})
Listener = Literal["web", "cloud", "debug"]


def new_correlation_id() -> str:
    return uuid4().hex


def current_context() -> dict[str, str]:
    """Return a copy so callers cannot mutate another operation's context."""
    return dict(_CONTEXT.get() or {})


def current_correlation_id() -> str | None:
    context = current_context()
    return context.get("job_id") or context.get("request_id")


@contextmanager
def correlation_scope(*, request_id: str | None = None, job_id: str | None = None) -> Iterator[None]:
    context = {}
    for key, value in (("request_id", request_id), ("job_id", job_id)):
        if value is not None:
            if not _ID.fullmatch(value):
                raise ValueError("invalid locally generated correlation ID")
            context[key] = value
    token = _CONTEXT.set(context)
    try:
        yield
    finally:
        _CONTEXT.reset(token)


def request_id_from_scope(scope: Scope) -> str | None:
    state = scope.get("state", {})
    value = state.get("request_id") if isinstance(state, dict) else None
    return value if isinstance(value, str) and _ID.fullmatch(value) else None


class RequestObservability:
    """Pure ASGI middleware: preserve streaming, cancellation and error behavior.

Only the matched route template, HTTP method, status and elapsed time enter the
completion event. Raw paths, query strings, headers, bodies and client identity
are deliberately absent. Unknown routes are a constant, not the requested URL.
"""

    def __init__(self, app: ASGIApp, *, listener: Listener) -> None:
        self.app = app
        self.listener = listener

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return
        # Local import avoids a cycle: the masterlog reads the same context.
        from basswiesn.app.core.masterlog import write_masterlog

        request_id = new_correlation_id()
        scope.setdefault("state", {})["request_id"] = request_id
        started = time.monotonic()
        status = 500
        outcome = "completed"

        async def send_correlated(message: Message) -> None:
            nonlocal status
            if message["type"] == "http.response.start":
                status = message["status"]
                message = dict(message)
                message["headers"] = [
                    (key, value) for key, value in message.get("headers", [])
                    if key.lower() != b"x-request-id"
                ] + [(b"x-request-id", request_id.encode("ascii"))]
            await send(message)

        with correlation_scope(request_id=request_id):
            try:
                await self.app(scope, receive, send_correlated)
            except asyncio.CancelledError:
                outcome = "cancelled"
                raise
            except Exception:
                outcome = "failed"
                raise
            finally:
                route = getattr(scope.get("route"), "path", None)
                method = scope.get("method", "")
                # Routine health and static/media polling still receive an ID,
                # but do not force a synchronous fsync for every successful poll.
                path = scope.get("path", "")
                quiet = (path in {"/live", "/ready", "/api/health"}
                         or path.startswith(("/static/", "/media/")))
                if not (quiet and status < 400 and outcome == "completed"):
                    try:
                        write_masterlog(
                            "http_request_completed",
                            listener=self.listener,
                            method=method if method in _METHODS else "OTHER",
                            route=route if isinstance(route, str) else "<unmatched>",
                            status_code=status,
                            outcome=outcome,
                            duration_ms=max(0, int((time.monotonic() - started) * 1000)),
                        )
                    except Exception:
                        # Observability must never mask a transport/cancellation
                        # error or turn a completed response into a failure.
                        pass


def install_request_observability(app: FastAPI, *, listener: Listener) -> None:
    """Install last so authorization failures also receive a correlation ID."""
    app.add_middleware(RequestObservability, listener=listener)
